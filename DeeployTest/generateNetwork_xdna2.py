    parser.add_argument('--trace-buffer-size',
                        type = int,
                        default = 8192,
                        help = 'Trace buffer size in bytes (default: 8192)')
    parser.add_argument('--trace-shim-col',
                        type = int,
                        default = 7,
                        help = 'Shim column to egress trace packets through (default: 7, '
                        'the rightmost shim on npu2).')
    parser.add_argument('--trace-tiles',
                        type = str,
                        default = None,
                        help = 'Comma-separated tile selector for tracing, e.g. "c0r2,c1r2". '
                        'Only meaningful with --trace. If omitted, every active core is traced.')
    parser.add_argument('--num-col',
                        type = int,
                        default = 1,
                        help = f'Number of AIE columns to use (1..{NPU2_NUM_COLS}, default: 1).')
    parser.add_argument('--num-aie-row',
                        type = int,
                        default = 1,
                        help = f'Number of AIE compute rows per column to use (1..{NPU2_NUM_AIE_ROWS}, '
                        f'default: 1). Total active AIE compute tiles = num-col * num-aie-row.')
    parser.add_argument('--data-mode',
                        type = str,
                        choices = ['auto', 'embed', 'file'],
                        default = 'auto',
                        help = 'Where test inputs/outputs live. "embed" inlines them in the test '
                        'header (good for small tensors), "file" dumps them to .bin sidecars (needed '
                        'for >32 MiB tensors), "auto" picks per size (default).')
    args, _ = parser.parse_known_args()

    if args.platform != 'XDNA2':
        parser.error(f"This script is for the XDNA2 platform. Got: {args.platform}")

    generateNetworkXDNA2(args)
